# Each selectable region also accepts all its listed registration codes.
_REGION_BY_CODE: dict[str, Region] = {
    code: region
    for region in REGIONS
    for code in region.registration_codes
}

# Kept as a separate name for the UI and existing bot imports.
UNIQUE_REGIONS: tuple[Region, ...] = tuple(sorted(REGIONS, key=lambda region: int(region.code)))


def get_region(code: str) -> Region | None:
    return _REGION_BY_CODE.get(code)


def registration_codes_for(code: str) -> tuple[str, ...]:
    region = get_region(code)
    return region.registration_codes if region else (code,)


def region_multiplier(code: str) -> float:
    region = get_region(code)
    return REGION_MULTIPLIERS.get(region.code if region else code, 0.50)


def spin_cost_for_region(code: str) -> int:
    from game_config import global_spin_cost

    return round(
        global_spin_cost()
        * region_multiplier(code)
        * REGIONAL_GUARANTEE_MULTIPLIER
    )


def region_value_bonus(tier: int) -> int:
    return {1: 520, 2: 280, 3: 120, 4: 40}.get(tier, 120)
